"""Turn a decompilation's land data and events into a map file.

The caller names the matrix and the cells (row, col) that make the map, the
events files to read, and optionally a crop (a world box of tiles) and a
tile whose walkable component the map is restricted to. The generator:

- decodes each tile to a cell (`landdata`), loading the matrix cells a crop
  reaches into as well; a tile in the box that no matrix cell covers is
  `unknown`;
- puts signposts on their tiles as sign cells and sign records, Rock Smash
  rocks as `rock` cells, item balls, boulders and Cut trees as standing
  objects (they block until removed), and people as NPCs with facing, sight
  and wander rectangles; objects a story flag hides go into a note, since
  whether they stand there depends on progress;
- reads warps, and connections from the matrix cells past each edge of the
  box, assuming each neighbour map is generated whole (its tile (0, 0) at
  the top-left of its cells);
- says where wild battles start from the tiles (grass, water, cave floor);
- records the repository, commit and files in `source` and a note.

Map coordinates are world coordinates minus the box's top-left corner, so a
whole-cell map's tile (x, y) is world (x0 + x, z0 + y).

    repo = open_repo("pokediamond", "~/pokediamond")
    route = generate(repo, "Route 201", "bdsp", Selection(0, [(26, 3), (26, 4)], ["327"]))
    route.grid.width, route.grid.height          # (64, 32)
"""

from typing import Dict, Iterable, List, NamedTuple, Optional, Sequence, Set, Tuple

from pokenav.decomp import landdata
from pokenav.decomp.events import Events, Kind, ObjectEvent
from pokenav.decomp.landdata import CELL_SIZE, UNKNOWN_CELL, LandGrid, Matrix
from pokenav.decomp.repos import OWNER, Repo
from pokenav.grid.geometry import CLOCKWISE, Direction, Tile
from pokenav.grid.maps.model import LEDGE_DIRECTION, Behavior, Cell, GridMap2D
from pokenav.grid.maps.schema import Connection, Encounter, MapFile, Note, Npc, Sign, Wander, Warp

#   The status every generated map starts with.
GENERATED_STATUS = "generated from the decomp, console checks pending"

#   Headers that are not maps: the matrix filler cell.
_NOT_A_MAP = ("EVERYWHERE",)

SIGN_CELL = Cell(blocked=True, behavior=Behavior.SIGN)
ROCK_CELL = Cell(blocked=True, behavior=Behavior.ROCK)

#   What the standing objects that are not people are called in notes.
_OBJECT_NOTES = {
    Kind.ITEM: "item ball; blocks its tile until picked up",
    Kind.BOULDER: "Strength boulder; blocks until pushed",
    Kind.TREE: "Cut tree; blocks until cut",
}

#   Platinum's events files repeat the neighbours' border objects, hidden
#   behind the neighbour's header; the neighbour's own file has them.
_NEIGHBOUR_COPY = "MAP_HEADER_"


class Selection(NamedTuple):
    """What to generate: the matrix, its cells (row, col), the events files
    (`Repo.events` specs), an optional world box (x0, z0, width, height)
    and an optional world tile whose walkable component is kept."""

    matrix: int
    cells: Sequence[Tuple[int, int]]
    events: Sequence[str] = ()
    crop: Optional[Tuple[int, int, int, int]] = None
    component: Optional[Tuple[int, int]] = None


class Box(NamedTuple):
    """A world box of tiles."""

    x0: int
    z0: int
    width: int
    height: int

    def contains(self, x: int, z: int) -> bool:
        return self.x0 <= x < self.x0 + self.width and self.z0 <= z < self.z0 + self.height

    def tile(self, x: int, z: int) -> Tile:
        """The map tile of world (x, z)."""
        return Tile(x - self.x0, z - self.z0)


def generate(repo: Repo, name: str, game: str, selection: Selection) -> MapFile:
    """The map file for `selection` read from `repo`."""
    matrix = repo.matrix(selection.matrix)
    land = _load(repo, matrix, selection.cells)
    box = Box(*selection.crop) if selection.crop else Box(*land.bounds())
    if selection.crop:
        _load_margins(repo, matrix, land, box)
    cells, cave = _cells(land, box)
    grid = GridMap2D(name, cells)
    headers = {matrix.headers[r][c] for r, c in selection.cells}
    source = _source(repo, matrix, land, selection)
    map_file = MapFile(
        grid=grid,
        game=game,
        source=source,
        status=GENERATED_STATUS,
        connections=_connections(matrix, box, headers, repo),
        notes=[Note("generated by pokenav.cli.decomp from %s" % source,
                    "%s@%s" % (repo.repository, repo.commit[:7]))],
    )
    for spec in selection.events:
        _add_events(map_file, box, repo.events(spec), repo)
    _name_apart(map_file.npcs)
    _name_apart(map_file.signs)
    map_file.encounters = _encounters(grid, cave)
    map_file.notes += _tile_notes(land, box)
    if selection.component is not None:
        restrict_to_component(map_file, box.tile(*selection.component))
    return map_file


#   ---- cells ----

def _load(repo: Repo, matrix: Matrix, cells: Iterable[Tuple[int, int]]) -> LandGrid:
    land = LandGrid()
    for row, col in cells:
        number = _map_in(matrix, row, col)
        if number is None:
            raise ValueError("matrix %r has no map in cell (%d, %d)" % (matrix.name, row, col))
        land.add(row, col, repo.land(number))
    return land


def _load_margins(repo: Repo, matrix: Matrix, land: LandGrid, box: Box) -> None:
    """Loads the matrix cells the box reaches into beyond the named ones,
    so a crop with a margin shows the neighbours' tiles; cells the matrix
    has no map for stay unknown."""
    loaded = set(land.cells())
    for row in _cell_range(box.z0, box.height):
        for col in _cell_range(box.x0, box.width):
            number = _map_in(matrix, row, col)
            if (row, col) not in loaded and number is not None:
                land.add(row, col, repo.land(number))


def _map_in(matrix: Matrix, row: int, col: int) -> Optional[int]:
    if 0 <= row < matrix.height and 0 <= col < matrix.width:
        return matrix.maps[row][col]
    return None


def _cells(land: LandGrid, box: Box) -> Tuple[List[List[Cell]], bool]:
    """The cells of the box, and whether any tile is cave floor."""
    rows = []
    cave = False
    for z in range(box.z0, box.z0 + box.height):
        row = []
        for x in range(box.x0, box.x0 + box.width):
            attr = land.attribute(x, z)
            if attr is None:
                row.append(UNKNOWN_CELL)
            else:
                row.append(landdata.cell(attr))
                cave = cave or landdata.is_cave_floor(attr)
        rows.append(row)
    return rows, cave


def _encounters(grid: GridMap2D, cave: bool) -> Set[Encounter]:
    kinds = set()
    behaviors = {cell.behavior for row in grid.rows() for cell in row}
    if Behavior.TALL_GRASS in behaviors:
        kinds.add(Encounter.GRASS)
    if Behavior.WATER in behaviors:
        kinds.add(Encounter.WATER)
    if cave:
        kinds.add(Encounter.CAVE)
    return frozenset(kinds)


def _tile_notes(land: LandGrid, box: Box) -> List[Note]:
    """Notes on tiles the model simplifies: one-way blocks, two-tile ledges,
    and tiles no cell covers."""
    one_way: List[Tile] = []
    double: List[Tile] = []
    unknown = 0
    for z in range(box.z0, box.z0 + box.height):
        for x in range(box.x0, box.x0 + box.width):
            attr = land.attribute(x, z)
            if attr is None:
                unknown += 1
                continue
            number = landdata.behavior_number(attr)
            if number in landdata.ONE_WAY_BLOCKS:
                one_way.append(box.tile(x, z))
            if number in landdata.DOUBLE_JUMPS:
                double.append(box.tile(x, z))
    notes = []
    if one_way:
        notes.append(Note("one-way blocks imported as plain ground at %s" % _tiles(one_way), "decomp"))
    if double:
        notes.append(Note("two-tile ledges (jump twice) imported as ledges at %s" % _tiles(double), "decomp"))
    if unknown:
        notes.append(Note("%d tiles of the box lie outside the generated cells and are unknown" % unknown, "decomp"))
    return notes


def _tiles(tiles: Sequence[Tile]) -> str:
    return ", ".join("(%d, %d)" % tile for tile in tiles)


#   ---- events ----

def _add_events(map_file: MapFile, box: Box, events: Events, repo: Repo) -> None:
    hidden = []
    for obj in events.objects:
        if not box.contains(obj.x, obj.z) or obj.hidden.startswith(_NEIGHBOUR_COPY):
            continue
        tile = box.tile(obj.x, obj.z)
        if obj.kind is Kind.SIGN:
            map_file.grid.set(tile, SIGN_CELL)
            map_file.signs.append(Sign(obj.name, tile, Direction.NORTH, obj.graphic))
        elif obj.kind is Kind.ROCK:
            map_file.grid.set(tile, ROCK_CELL)
        elif obj.kind in _OBJECT_NOTES:
            map_file.npcs.append(Npc(obj.name, tile, note=_OBJECT_NOTES[obj.kind] + _hidden_note(obj)))
        elif obj.hidden:
            hidden.append("%s at %s (%s)" % (obj.name, tile, obj.hidden))
        else:
            map_file.npcs.append(_npc(obj, tile))
    if hidden:
        map_file.notes.append(Note("objects a story flag hides, not placed: " + "; ".join(hidden), "decomp"))
    for warp in events.warps:
        if box.contains(warp.x, warp.z):
            map_file.warps.append(Warp(box.tile(warp.x, warp.z), repo.map_name(warp.to_map), warp.to_warp))
    for sign in events.signs:
        if box.contains(sign.x, sign.z):
            map_file.signs.append(Sign("sign_script_%d" % sign.script, box.tile(sign.x, sign.z), Direction.NORTH,
                                       "background sign event; the tile is as the land data says"))


def _hidden_note(obj: ObjectEvent) -> str:
    return " (%s)" % obj.hidden if obj.hidden else ""


def _npc(obj: ObjectEvent, tile: Tile) -> Npc:
    wander = None
    if obj.wanders:
        wander = Wander(Tile(tile.x - obj.range_x, tile.y - obj.range_z),
                        Tile(tile.x + obj.range_x, tile.y + obj.range_z))
    return Npc(obj.name, tile, facing=obj.facing, sight=obj.sight, wander=wander,
               note="%s, %s" % (obj.graphic, obj.movement))


def _name_apart(records) -> None:
    """Gives records that share a name a number each, in order."""
    counts: Dict[str, int] = {}
    for record in records:
        counts[record.name] = counts.get(record.name, 0) + 1
    seen: Dict[str, int] = {}
    for record in records:
        if counts[record.name] > 1:
            seen[record.name] = seen.get(record.name, 0) + 1
            record.name = "%s_%d" % (record.name, seen[record.name])


#   ---- connections ----

def _connections(matrix: Matrix, box: Box, headers: Set[Optional[str]], repo: Repo) -> List[Connection]:
    """A connection per neighbour map across each edge of the box. The
    neighbour's origin is the top-left of its cells, so the offset is
    right when it is generated whole."""
    connections = []
    for direction in CLOCKWISE:
        for header in _neighbours(matrix, box, direction):
            if header in headers or header is None or any(word in header for word in _NOT_A_MAP):
                continue
            origin = matrix.origin_of(header)
            if origin is None:
                continue
            ox, oz = origin
            offset = ox - box.x0 if direction.is_vertical else oz - box.z0
            connections.append(Connection(direction, repo.map_name(header), offset))
    return connections


def _neighbours(matrix: Matrix, box: Box, direction: Direction) -> List[Optional[str]]:
    """The headers of the cells just past the box's edge in `direction`,
    west to east or north to south, without repeats."""
    if direction is Direction.NORTH:
        rows, cols = [(box.z0 - 1) // CELL_SIZE], _cell_range(box.x0, box.width)
    elif direction is Direction.SOUTH:
        rows, cols = [(box.z0 + box.height) // CELL_SIZE], _cell_range(box.x0, box.width)
    elif direction is Direction.WEST:
        rows, cols = _cell_range(box.z0, box.height), [(box.x0 - 1) // CELL_SIZE]
    else:
        rows, cols = _cell_range(box.z0, box.height), [(box.x0 + box.width) // CELL_SIZE]
    headers: List[Optional[str]] = []
    for row in rows:
        for col in cols:
            header = matrix.header_at(row, col)
            if header not in headers:
                headers.append(header)
    return headers


def _cell_range(start: int, length: int) -> List[int]:
    return list(range(start // CELL_SIZE, (start + length - 1) // CELL_SIZE + 1))


#   ---- source ----

def _source(repo: Repo, matrix: Matrix, land: LandGrid, selection: Selection) -> str:
    files = [repo.land_path(matrix.maps[r][c]) for r, c in land.cells()]
    files.append(repo.matrix_path(selection.matrix))
    files += [repo.events_path(spec) for spec in selection.events]
    return "%s@%s: %s" % (repo.repository, repo.commit[:7] or "?", ", ".join(files))


#   ---- components ----

def passable(cell: Optional[Cell]) -> bool:
    """Whether a walker can stand on the cell."""
    return cell is not None and not cell.blocked and cell.behavior is not Behavior.UNKNOWN


def walkable_components(grid: GridMap2D) -> List[Set[Tile]]:
    """The connected sets of passable tiles, largest first. Two tiles are
    joined by a step between them, by a hop over a ledge between them (in
    either direction, since a map is one place however it is entered), or
    by a rock between them that Rock Smash clears."""
    seen: Set[Tile] = set()
    components = []
    for start in grid.tiles():
        if start in seen or not passable(grid.at(start)):
            continue
        component = {start}
        queue = [start]
        while queue:
            tile = queue.pop()
            for neighbour in _joined(grid, tile):
                if neighbour not in component:
                    component.add(neighbour)
                    queue.append(neighbour)
        seen |= component
        components.append(component)
    return sorted(components, key=len, reverse=True)


def _joined(grid: GridMap2D, tile: Tile) -> Iterable[Tile]:
    for direction in CLOCKWISE:
        step = tile.step(direction)
        cell = grid.at(step)
        if passable(cell):
            yield step
        elif cell is not None and _crossable(cell, direction):
            beyond = step.step(direction)
            if passable(grid.at(beyond)):
                yield beyond


def _crossable(cell: Cell, direction: Direction) -> bool:
    """Whether a blocked cell joins the tiles either side of it along
    `direction`: a ledge along its axis, or a rock."""
    if cell.behavior is Behavior.ROCK:
        return True
    return LEDGE_DIRECTION.get(cell.behavior) in (direction, direction.opposite)


def restrict_to_component(map_file: MapFile, tile: Tile) -> int:
    """Keeps the walkable component holding `tile` and turns every other
    passable tile unknown, so the map is one place (one map, one connected
    component); connections off edges the kept component does not reach are
    dropped. Returns how many tiles changed. Raises ValueError if `tile` is
    not passable."""
    grid = map_file.grid
    components = walkable_components(grid)
    kept = next((c for c in components if tile in c), None)
    if kept is None:
        raise ValueError("%s is not a walkable tile of %r" % (tile, grid.name))
    changed = 0
    for other in components:
        if other is kept:
            continue
        for lost in other:
            grid.set(lost, UNKNOWN_CELL)
            changed += 1
    map_file.connections = [c for c in map_file.connections if _reaches_edge(grid, kept, c.direction)]
    if changed:
        map_file.notes.append(Note("%d walkable tiles not connected to %s are unknown: they are other "
                                   "components of the game map (one map, one connected component)"
                                   % (changed, tile), "generator"))
    return changed


def _reaches_edge(grid: GridMap2D, component: Set[Tile], direction: Direction) -> bool:
    edge = {Direction.NORTH: lambda t: t.y == 0, Direction.SOUTH: lambda t: t.y == grid.height - 1,
            Direction.WEST: lambda t: t.x == 0, Direction.EAST: lambda t: t.x == grid.width - 1}[direction]
    return any(edge(tile) for tile in component)


#   ---- keeping hand records ----

def keep_records(generated: MapFile, kept: MapFile) -> MapFile:
    """Carries a hand-edited map file's records into a regenerated one, in
    the same frame: its named points, buildings, notes and status; the
    names and notes of its NPCs for the generated NPCs on the same tiles;
    and its other NPCs as they are (people placed from the console that the
    decomp hides behind a story flag). Its generated notes (source "decomp",
    "generator" or a repository at a commit) are not repeated."""
    generated.points = list(kept.points)
    generated.buildings = list(kept.buildings)
    generated.notes = generated.notes + [n for n in kept.notes if not _generated_note(n)]
    if kept.status:
        generated.status = kept.status
    by_tile = {npc.tile: npc for npc in kept.npcs}
    for npc in generated.npcs:
        old = by_tile.pop(npc.tile, None)
        if old is not None:
            npc.name = old.name
            npc.note = _merged_note(npc.note, old.note)
    generated.npcs += list(by_tile.values())
    return generated


def _merged_note(generated: str, kept: str) -> str:
    """The generated note, then the kept one. A kept note that already
    starts with the generated one (a file regenerated with itself kept) is
    kept as it is, so regenerating is stable."""
    if not kept or kept == generated:
        return generated
    if not generated or kept.startswith(generated):
        return kept
    return "%s. %s" % (generated, kept)


def _generated_note(note: Note) -> bool:
    """Whether the generator wrote the note: its sources are "decomp",
    "generator" and the repository with its commit ("pret/pokediamond@b623abe")."""
    return note.source in ("decomp", "generator") or (note.source.startswith("%s/" % OWNER) and "@" in note.source)
